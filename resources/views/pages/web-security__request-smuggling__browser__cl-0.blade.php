        <h1 class="heading-2">CL.0 request smuggling</h1><p>
            Request smuggling vulnerabilities are the result of discrepancies in how chained systems determine where each request starts and ends. This is typically due to <a href="/web-security/request-smuggling#how-do-http-request-smuggling-vulnerabilities-arise">inconsistent header parsing</a>, leading to one server using a request's <code>Content-Length</code> and the other treating the message as chunked. However, it's possible to perform many of the same attacks without relying on either of these issues.
        </p><p>
            In some instances, servers can be persuaded to ignore the <code>Content-Length</code> header, meaning they assume that each request finishes at the end of the headers. This is effectively the same as treating the <code>Content-Length</code> as <code>0</code>.
        </p><p>
            If the back-end server exhibits this behavior, but the front-end still uses the <code>Content-Length</code> header to determine where the request ends, you can potentially exploit this discrepancy for HTTP request smuggling. We've decided to call this a "CL.0" vulnerability.
        </p><div class="highlightedarea">
            <h4>SecDevLab Research</h4>
            <p>
                The materials and labs in this section are based on <a href="https://portswigger.net/research/browser-powered-desync-attacks">Browser-Powered Desync Attacks: A New Frontier in HTTP Request Smuggling</a> by SecDevLab Research.
            </p>
        </div><h2 id="testing-for-cl-0-vulnerabilities">Testing for CL.0 vulnerabilities</h2><p>
            To probe for CL.0 vulnerabilities, first send a request containing another partial request in its body, then send a normal follow-up request. You can then check to see whether the response to the follow-up request was affected by the smuggled prefix.
        </p><p>
            In the following example, the follow-up request for the home page has received a 404 response. This strongly suggests that the back-end server interpreted the body of the <code>POST</code> request (<code>GET /hopefully404...</code>) as the start of another request.
        </p><div class="container-code pre-wrap">
<code class="margin-none theme-white pre-wrap">POST /vulnerable-endpoint HTTP/1.1
Host: vulnerable-website.com
Connection: keep-alive
Content-Type: application/x-www-form-urlencoded
Content-Length: 34

<span class="orange">GET /hopefully404 HTTP/1.1
Foo: x</span><span class="green">GET / HTTP/1.1
Host: vulnerable-website.com</span></code>
<code class="margin-none theme-community-6 pre-wrap">HTTP/1.1 200 OK






<span class="orange">HTTP/1.1 404 Not Found</span></code>
        </div><p>
            Crucially, notice that we haven't tampered with the headers in any way - the length of the request is specified by a perfectly normal, accurate <code>Content-Length</code> header.
        </p><p>
            To try this yourself using Burp Repeater:
        </p><ol>
            <li>
                <p>
                    Create one tab containing the setup request and another containing an arbitrary follow-up request.
                </p>
            </li>
            <li>
                <p>
                    Add the two tabs to a group in the correct order.
                </p>
            </li>
            <li>
                <p>
                    Using the drop-down menu next to the <strong>Send</strong> button, change the send mode to <strong>Send group in sequence (single connection)</strong>.
                </p>
            </li>
            <li>
                <p>
                    Change the <code>Connection</code> header to <code>keep-alive</code>.
                </p>
            </li>
            <li>
                <p>
                    Send the sequence and check the responses.
                </p>
            </li>
        </ol><p>
            In the wild, we've mostly observed this behavior on endpoints that simply aren't expecting <code>POST</code> requests, so they implicitly assume that no requests have a body. Endpoints that trigger server-level redirects and requests for static files are prime candidates.
        </p><h2 id="eliciting-cl-0-behavior">Eliciting CL.0 behavior</h2><p>
            If you can't find any endpoints that appear vulnerable, you can try eliciting this behavior instead.
        </p><p>
            When a request's headers trigger a server error, some servers issue an error response without consuming the request body off the socket. If they don't close the connection afterwards, this can provide an alternative CL.0 desync vector.
        </p><p>
            You can also try using <code>GET</code> requests with an obfuscated <code>Content-Length</code> header. If you're able to hide this from the back-end server but not the front-end, this also has the potential to cause a desync. We looked at some <a href="/web-security/request-smuggling#te-te-behavior-obfuscating-the-te-header">header obfuscation techniques</a> when we covered TE.TE request smuggling.
        </p><h2 id="exploiting-cl-0-vulnerabilities">Exploiting CL.0 vulnerabilities</h2><p>
