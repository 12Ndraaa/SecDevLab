			Another common technique is to use a <code>form</code> element along with an element such as <code>input</code> to clobber DOM properties. For example, clobbering the <code>attributes</code> property enables you to bypass client-side filters that use it in their logic. Although the filter will enumerate the <code>attributes</code> property, it will not actually remove any attributes because the property has been clobbered with a DOM node. As a result, you will be able to inject malicious attributes that would normally be filtered out. For example, consider the following injection:
        </p><code class="code-scrollable">&lt;form onclick=alert(1)&gt;&lt;input id=attributes&gt;Click me</code><p>
            In this case, the client-side filter would traverse the DOM and encounter a whitelisted <code>form</code> element. Normally, the filter would loop through the <code>attributes</code> property of the <code>form</code> element and remove any blacklisted attributes. However, because the <code>attributes</code> property has been clobbered with the <code>input</code> element, the filter loops through the <code>input</code> element instead. As the <code>input</code> element has an undefined length, the conditions for the <code>for</code> loop of the filter (for example <code>i&lt;element.attributes.length</code>) are not met, and the filter simply moves on to the next element instead. This results in the <code>onclick</code> event being ignored altogether by the filter, which subsequently allows the <code>alert()</code> function to be called in the browser.
