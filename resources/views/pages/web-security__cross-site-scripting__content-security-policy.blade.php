        <h1 class="heading-2">Content security policy</h1><p>
            In this section, we'll explain what content security policy is, and describe how CSP can be used to mitigate against some common attacks.
        </p><h2 id="what-is-csp-content-security-policy">What is CSP (content security policy)?</h2><p>
            CSP is a browser security mechanism that aims to mitigate XSS and some other attacks. It works by restricting the resources (such as scripts and images) that a page can load and restricting whether a page can be framed by other pages.
        </p><p>
            To enable CSP, a response needs to include an HTTP response header called <code>Content-Security-Policy</code> with a value containing the policy. The policy itself consists of one or more directives, separated by semicolons.
        </p><h2 id="mitigating-xss-attacks-using-csp">Mitigating XSS attacks using CSP</h2><p>
            The following directive will only allow scripts to be loaded from the <a href="/web-security/cors/same-origin-policy">same origin</a> as the page itself:
        </p><code class="code-scrollable">script-src 'self'</code><p>
            The following directive will only allow scripts to be loaded from a specific domain:
        </p><code class="code-scrollable">script-src https://scripts.normal-website.com</code><p>
            Care should be taken when allowing scripts from external domains. If there is any way for an attacker to control content that is served from the external domain, then they might be able to deliver an attack. For example, content delivery networks (CDNs) that do not use per-customer URLs, such as <code>ajax.googleapis.com</code>, should not be trusted, because third parties can get content onto their domains.
        </p><p>
            In addition to whitelisting specific domains, content security policy also provides two other ways of specifying trusted resources: nonces and hashes:
        </p><ul>
            <li>
                The CSP directive can specify a nonce (a random value) and the same value must be used in the tag that loads a script. If the values do not match, then the script will not execute. To be effective as a control, the nonce must be securely generated on each page load and not be guessable by an attacker.
            </li>
            <li>
                The CSP directive can specify a hash of the contents of the trusted script. If the hash of the actual script does not match the value specified in the directive, then the script will not execute. If the content of the script ever changes, then you will of course need to update the hash value that is specified in the directive.
            </li>
        </ul><p>
			It's quite common for a CSP to block resources like <code>script</code>. However, many CSPs do allow image requests. This means you can often use <code>img</code> elements to make requests to external servers in order to disclose CSRF tokens, for example.
		</p><p>
			Some browsers, such as Chrome, have built-in dangling markup mitigation that will block requests containing certain characters, such as raw, unencoded new lines or angle brackets.
        </p><p>
            Some policies are more restrictive and prevent all forms of external requests. However, it's still possible to <a href="https://portswigger.net/research/evading-csp-with-dom-based-dangling-markup">get round these restrictions by eliciting some user interaction</a>. To bypass this form of policy, you need to inject an HTML element that, when clicked, will store and send everything enclosed by the injected element to an external server.
