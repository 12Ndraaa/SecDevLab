            The following directive will only allow the page to be framed by other pages from the same origin:
        </p><code class="code-scrollable">frame-ancestors 'self'</code><p>
            The following directive will prevent framing altogether:
        </p><code class="code-scrollable">frame-ancestors 'none'</code><p>
            Using content security policy to prevent clickjacking is more flexible than using the X-Frame-Options header because you can specify multiple domains and use wildcards. For example:
        </p><code class="code-scrollable">frame-ancestors 'self' https://normal-website.com https://*.robust-website.com</code><p>
            CSP also validates each frame in the parent frame hierarchy, whereas <code>X-Frame-Options</code> only validates the top-level frame.
        </p><p>
            Using CSP to protect against clickjacking attacks is recommended. You can also combine this with the <code>X-Frame-Options</code> header to provide protection on older browsers that don't support CSP, such as Internet Explorer.
