            The following directive will only allow images to be loaded from the same origin as the page itself:
        </p><code class="code-scrollable">img-src 'self'</code><p>
            The following directive will only allow images to be loaded from a specific domain:
        </p><code class="code-scrollable">img-src https://images.normal-website.com</code><p>
            Note that these policies will prevent some dangling markup exploits, because an easy way to capture data with no user interaction is using an <code>img</code> tag. However, it will not prevent other exploits, such as those that inject an anchor tag with a dangling <code>href</code> attribute.
		</p><h2 id="bypassing-csp-with-policy-injection">Bypassing CSP with policy injection</h2><p>
			You may encounter a website that reflects input into the actual policy, most likely in a <code>report-uri</code> directive. If the site reflects a parameter that you can control, you can inject a semicolon to add your own CSP directives. Usually, this <code>report-uri</code> directive is the final one in the list. This means you will need to overwrite existing directives in order to exploit this vulnerability and bypass the policy.
